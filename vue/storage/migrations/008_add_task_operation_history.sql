-- User-facing, bounded task history. The immutable audit log remains independent.
CREATE TABLE IF NOT EXISTS public.rpa_task_operation_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  audit_log_id BIGINT NOT NULL UNIQUE REFERENCES public.rpa_task_audit_log(id) ON DELETE RESTRICT,
  task_id BIGINT NOT NULL REFERENCES public.rpa_tasks(id) ON DELETE RESTRICT,
  task_name TEXT NOT NULL,
  actor_user_id BIGINT REFERENCES public.app_users(id) ON DELETE RESTRICT,
  action TEXT NOT NULL CHECK (action IN ('create', 'update', 'delete', 'import', 'rebind', 'transfer', 'admin_recover', 'run_now', 'restore')),
  before_snapshot JSONB,
  after_snapshot JSONB,
  snapshot_complete BOOLEAN NOT NULL DEFAULT TRUE,
  before_version INTEGER,
  after_version INTEGER,
  annotation TEXT NOT NULL DEFAULT '' CHECK (length(annotation) <= 1000),
  annotation_version INTEGER NOT NULL DEFAULT 0 CHECK (annotation_version >= 0),
  annotation_updated_at TIMESTAMPTZ,
  source_audit_id BIGINT REFERENCES public.rpa_task_audit_log(id) ON DELETE RESTRICT,
  reverted_by_audit_id BIGINT REFERENCES public.rpa_task_audit_log(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX idx_task_operation_history_task_recent
  ON public.rpa_task_operation_history (task_id, created_at DESC, id DESC);
CREATE INDEX idx_task_operation_history_recent
  ON public.rpa_task_operation_history (id DESC);
CREATE INDEX idx_task_operation_history_actor_recent
  ON public.rpa_task_operation_history (actor_user_id, id DESC);

ALTER TABLE public.rpa_task_audit_log DROP CONSTRAINT ck_rpa_task_audit_log_action;
ALTER TABLE public.rpa_task_audit_log ADD CONSTRAINT ck_rpa_task_audit_log_action
  CHECK (action IN ('create', 'update', 'delete', 'rebind', 'transfer', 'import', 'run_now', 'admin_recover', 'restore')) NOT VALID;

-- Older audits contain partial field values, not full historical snapshots.
-- Expose the newest 50 per task as read-only history; never fabricate snapshots.
INSERT INTO public.rpa_task_operation_history
  (audit_log_id, task_id, task_name, actor_user_id, action, snapshot_complete, created_at)
SELECT entry.id, entry.task_id,
       COALESCE(entry.new_value->>'task', entry.old_value->>'task', task.task),
       entry.actor_user_id, entry.action, FALSE, entry.created_at
FROM (
  SELECT audit.*, row_number() OVER (PARTITION BY task_id ORDER BY created_at DESC, id DESC) AS ordinal
  FROM public.rpa_task_audit_log AS audit
) AS entry
JOIN public.rpa_tasks AS task ON task.id = entry.task_id
WHERE entry.ordinal <= 50
ORDER BY entry.created_at, entry.id;
