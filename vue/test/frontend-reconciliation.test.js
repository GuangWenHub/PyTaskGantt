// @vitest-environment jsdom
import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const state = vi.hoisted(() => ({ confirm: null, start: vi.fn(), get: vi.fn(), apply: vi.fn(), rule: vi.fn(), restore: vi.fn(), recheck: vi.fn() }))
vi.mock('../src/services/scheduleReconciliationService.js', () => ({ startPlanScan: state.start, getPlanSyncState: state.get, changePlanWhitelist: state.rule, restorePlanWhitelist: state.restore, recheckPlanEntries: state.recheck, applyPlanChanges: state.apply }))
vi.mock('naive-ui', () => {
  const slot = { template: '<div><slot /></div>' }
  return { NModal: { props: ['show'], template: '<section v-if="show"><slot /></section>' }, NAlert: slot, NSpin: slot,
    NButton: { props: ['disabled'], emits: ['click'], template: '<button :disabled="disabled" @click="$emit(\'click\')"><slot /></button>' },
    NDataTable: { name: 'NDataTable', props: ['columns', 'data', 'checkedRowKeys', 'rowKey'], emits: ['update:checked-row-keys'], template: '<div />' },
    NTabs: { name: 'NTabs', props: ['value'], emits: ['update:value'], template: '<div><slot /></div>' }, NTabPane: slot,
    NDropdown: { name: 'NDropdown', props: ['options'], emits: ['select'], template: '<div><slot /></div>' },
    useMessage: () => ({ success: vi.fn() }), useDialog: () => ({ warning: options => { state.confirm = options } }),
  }
})
import ScheduleReconciliationDialog from '../src/components/ScheduleReconciliationDialog.vue'
import { planSyncStore } from '../src/stores/planSyncStore.js'
const entry = { id: 'entry-1', kind: 'update', task_id: '1', schedule_uuid: 'a', can_apply: true, fields: [{ field: 'start', label: '开始', local: '09:00', remote: '10:00' }] }
function view(entries = [entry]) { return { id: 'scan-1', state: 'ready', entries, unchanged: 2, scanned_at: new Date().toISOString() } }
function shared(entries = [entry], whitelist = []) { const result = view(entries); return { job: result, result, whitelist } }
describe('计划差异确认界面', () => {
  afterEach(() => { planSyncStore.connectUser(null) })
  beforeEach(() => { planSyncStore.connectUser(null); localStorage.clear(); vi.clearAllMocks(); state.confirm = null; state.start.mockResolvedValue(view()); state.get.mockResolvedValue(shared()); state.apply.mockResolvedValue({ success: true, affected_ids: ['1'] }) })
  it('扫描不写库，单条同步需确认，成功后通知页面刷新并移除已处理差异', async () => {
    planSyncStore.connectUser('1')
    await flushPromises()
    expect(planSyncStore.state.unread).toBe(true)
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    await flushPromises()
    expect(planSyncStore.state.unread).toBe(false)
    expect(state.start).not.toHaveBeenCalled()
    expect(state.apply).not.toHaveBeenCalled()
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'update')
    await flushPromises()
    const table = wrapper.findComponent({ name: 'NDataTable' })
    const action = table.props('columns').find(column => column.key === 'action').render(entry)
    action.children[0].props.onClick()
    expect(state.confirm.content).toContain('写入数据库')
    expect(state.apply).not.toHaveBeenCalled()
    state.get.mockResolvedValue(shared([{ ...entry, applied: true }]))
    await state.confirm.onPositiveClick()
    await flushPromises()
    expect(state.apply).toHaveBeenCalledWith('scan-1', ['entry-1'])
    expect(wrapper.emitted('applied')[0][0].affected_ids).toEqual(['1'])
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data')).toHaveLength(0)
    wrapper.unmount()
  })
  it('新增跳转预填卡片，不直接写入；无权限或另有草稿的记录不可选', async () => {
    const create = { ...entry, id: 'new', kind: 'create', defaults: { task: '计划名' }, task_id: null }
    state.get.mockResolvedValue(shared([create]))
    planSyncStore.connectUser('1')
    await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true, isTaskDirty: () => true } })
    await flushPromises()
    const columns = wrapper.findComponent({ name: 'NDataTable' }).props('columns')
    columns.find(column => column.key === 'action').render(create).children[0].props.onClick()
    expect(wrapper.emitted('create')[0][0]).toEqual({ snapshot_id: 'scan-1', entry: create })
    expect(state.apply).not.toHaveBeenCalled()
    expect(columns[0].disabled(entry)).toBe(true)
    expect(columns[0].disabled({ ...entry, can_apply: false })).toBe(true)
    wrapper.unmount()
  })
  it('反复打开直接读取缓存，不扫描；后台更新期间仍展示旧结果', async () => {
    planSyncStore.connectUser('1')
    await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'update')
    await flushPromises()
    await wrapper.setProps({ show: false })
    await wrapper.setProps({ show: true })
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data')).toHaveLength(1)
    expect(state.start).not.toHaveBeenCalled()
    expect(state.get).toHaveBeenCalledTimes(1)
    state.start.mockResolvedValue({ id: 'scan-2', state: 'scanning', entries: [] })
    await planSyncStore.scan()
    await flushPromises()
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data')).toHaveLength(1)
    expect(wrapper.text()).toContain('上次结果')
    expect(wrapper.text()).toContain('后台更新中')
    const columns = wrapper.findComponent({ name: 'NDataTable' }).props('columns')
    expect(columns[0].disabled(entry)).toBe(true)
    expect(state.start).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })
  it('差异旁逐属性加入数据库白名单，白名单页可以恢复，不直接修改任务', async () => {
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'update'); await flushPromises()
    const rule = { task_id: '1', schedule_uuid: 'a', field: 'start', name: '任务', can_edit: true }
    state.rule.mockResolvedValue(shared([entry], [rule]))
    const actionColumn = wrapper.findComponent({ name: 'NDataTable' }).props('columns').find(column => column.key === 'action')
    const rendered = actionColumn.render(entry)
    expect(rendered.props.class).toBe('reconciliation-row-actions')
    const ignore = rendered.children[1]
    const textButton = ignore.children.default()
    expect(textButton.props.text).toBe(true)
    expect(textButton.props.secondary).toBeUndefined()
    expect(ignore.props.options).toEqual([{ key: 'start', label: '忽略开始' }])
    await ignore.props.onSelect('start'); await flushPromises()
    expect(state.rule).toHaveBeenCalledWith({ task_id: '1', schedule_uuid: 'a', field: 'start' }, false)
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data')).toHaveLength(0)
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'whitelist'); await flushPromises()
    const table = wrapper.findComponent({ name: 'NDataTable' })
    expect(table.props('data')[0].label).toBe('开始时间')
    state.rule.mockResolvedValue(shared())
    await table.props('columns').find(column => column.key === 'action').render(table.props('data')[0]).props.onClick()
    expect(state.rule).toHaveBeenLastCalledWith({ task_id: '1', schedule_uuid: 'a', field: 'start' }, true)
    expect(state.apply).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('一键新增包含其他分页，确认后提交批量标记；顶部共享说明已删除', async () => {
    const entries = Array.from({ length: 12 }, (_, i) => ({ ...entry, id: `new-${i}`, kind: 'create', task_id: null }))
    state.get.mockResolvedValue(shared(entries))
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    expect(wrapper.text()).not.toContain('扫描结果与白名单由所有账号共享')
    const bulk = wrapper.findAll('button').find(button => button.text() === '一键新增（12）')
    await bulk.trigger('click')
    expect(state.confirm.content).toContain('包含其他分页中的勾选')
    expect(state.confirm.content).toContain('无有效记录时使用1分钟')
    expect(state.apply).not.toHaveBeenCalled()
    state.get.mockResolvedValue(shared(entries.map(row => ({ ...row, applied: true }))))
    await state.confirm.onPositiveClick(); await flushPromises()
    expect(state.apply).toHaveBeenCalledWith('scan-1', entries.map(row => row.id), undefined, { bulkCreate: true })
    expect(wrapper.emitted('applied')).toHaveLength(1)
    wrapper.unmount()
  })
  it.each([['create', '新增所选'], ['update', '同步所选'], ['delete', '移除所选']])('%s页仅提交勾选项，批量按钮与复选框对应', async (kind, label) => {
    const entries = ['chosen', 'untouched'].map(id => ({ ...entry, id, kind, task_id: kind === 'create' ? null : id }))
    state.get.mockResolvedValue(shared(entries))
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', kind); await flushPromises()
    const table = wrapper.findComponent({ name: 'NDataTable' })
    expect(table.props('columns')[0].disabled(entries[0])).toBe(false)
    table.vm.$emit('update:checked-row-keys', ['chosen']); await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === `${label}（1）`).trigger('click')
    expect(state.apply).not.toHaveBeenCalled()
    state.get.mockResolvedValue(shared([{ ...entries[0], applied: true }, entries[1]]))
    await state.confirm.onPositiveClick(); await flushPromises()
    if (kind === 'create') expect(state.apply).toHaveBeenCalledWith('scan-1', ['chosen'], undefined, { bulkCreate: true })
    else expect(state.apply).toHaveBeenCalledWith('scan-1', ['chosen'])
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data').map(row => row.id)).toEqual(['untouched'])
    wrapper.unmount()
  })
  it('白名单按属性独立勾选，只恢复所选的有权限属性', async () => {
    const rules = [{ task_id: '1', schedule_uuid: 'a', field: 'start', can_edit: true }, { task_id: '1', schedule_uuid: 'a', field: 'task', can_edit: true }, { task_id: '2', schedule_uuid: 'b', field: 'start', can_edit: false }]
    state.get.mockResolvedValue(shared([entry], rules))
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'whitelist'); await flushPromises()
    const table = wrapper.findComponent({ name: 'NDataTable' }), rows = table.props('data')
    const keys = rows.map(table.props('rowKey'))
    expect(new Set(keys).size).toBe(3)
    expect(table.props('columns')[0].disabled(rows[2])).toBe(true)
    table.vm.$emit('update:checked-row-keys', keys); await flushPromises()
    state.restore.mockResolvedValue(shared([entry], [rules[2]]))
    await wrapper.findAll('button').find(button => button.text() === '恢复所选提醒与同步（2）').trigger('click')
    await state.confirm.onPositiveClick(); await flushPromises()
    expect(state.restore).toHaveBeenCalledWith(rules.slice(0, 2).map(({ task_id, schedule_uuid, field }) => ({ task_id, schedule_uuid, field })))
    expect(state.apply).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('需人工处理可勾选重新核验，仅重读所选计划而不写任务或全量扫描', async () => {
    const entries = ['chosen', 'untouched'].map(id => ({ ...entry, id, kind: 'error', can_apply: false, fields: [], error: '读取失败' }))
    state.get.mockResolvedValue(shared(entries))
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'error'); await flushPromises()
    const table = wrapper.findComponent({ name: 'NDataTable' })
    expect(table.props('columns')[0].disabled(entries[0])).toBe(false)
    table.vm.$emit('update:checked-row-keys', ['chosen']); await flushPromises()
    state.recheck.mockResolvedValue(shared([{ ...entry, id: 'chosen' }, entries[1]]))
    await wrapper.findAll('button').find(button => button.text() === '重新核验所选（1）').trigger('click')
    await state.confirm.onPositiveClick(); await flushPromises()
    expect(state.recheck).toHaveBeenCalledWith('scan-1', ['chosen'])
    expect(state.apply).not.toHaveBeenCalled()
    expect(state.start).not.toHaveBeenCalled()
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data').map(row => row.id)).toEqual(['untouched'])
    wrapper.unmount()
  })
  it('待新增提供同样的浅色文字白名单入口，按计划忽略并支持恢复新增提醒', async () => {
    const create = { ...entry, id: 'new-plan', kind: 'create', task_id: null, fields: [] }
    const rule = { task_id: null, schedule_uuid: 'a', field: 'plan', name: '影刀计划', can_edit: true }
    state.get.mockResolvedValue(shared([create]))
    planSyncStore.connectUser('1'); await flushPromises()
    const wrapper = mount(ScheduleReconciliationDialog, { props: { show: true } })
    const table = wrapper.findComponent({ name: 'NDataTable' })
    const actions = table.props('columns').find(column => column.key === 'action').render(create)
    const add = actions.children[1]
    expect(add.props.class).toBe('reconciliation-ignore')
    expect(add.props.text).toBe(true)
    expect(add.props.secondary).toBeUndefined()
    state.rule.mockResolvedValue(shared([create], [rule]))
    await add.props.onClick(); await flushPromises()
    expect(state.rule).toHaveBeenCalledWith({ task_id: null, schedule_uuid: 'a', field: 'plan' }, false)
    expect(wrapper.findComponent({ name: 'NDataTable' }).props('data')).toHaveLength(0)
    expect(state.apply).not.toHaveBeenCalled()
    wrapper.findComponent({ name: 'NTabs' }).vm.$emit('update:value', 'whitelist'); await flushPromises()
    const whiteTable = wrapper.findComponent({ name: 'NDataTable' })
    expect(whiteTable.props('data')[0].label).toBe('新增提醒（整个计划）')
    state.rule.mockResolvedValue(shared([create]))
    await whiteTable.props('columns').find(column => column.key === 'action').render(whiteTable.props('data')[0]).props.onClick()
    expect(state.rule).toHaveBeenLastCalledWith({ task_id: null, schedule_uuid: 'a', field: 'plan' }, true)
    wrapper.unmount()
  })
})
