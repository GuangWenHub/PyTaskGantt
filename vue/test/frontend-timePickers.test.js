// @vitest-environment jsdom
import { mount } from '@vue/test-utils'
import { describe, expect, it, vi } from 'vitest'
vi.mock('naive-ui', () => ({ NPopover: { template: '<div><slot name="trigger" /><slot /></div>' } }))
import ClockTimePicker from '../src/components/ClockTimePicker.vue'
import DurationPicker from '../src/components/DurationPicker.vue'

describe('24小时表盘和手动输入', () => {
  it('表盘可选全部24小时、分钟和秒，保留手动输入及格式校验', async () => {
    const wrapper = mount(ClockTimePicker, { props: { value: '00:00:00', label: '开始时间' } })
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    await wrapper.get('input[aria-label="开始时间时"]').trigger('focus')
    expect(wrapper.findAll('.clock-dial button')).toHaveLength(24)
    await wrapper.get('button[aria-label="23时"]').trigger('click')
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['23:00:00'])
    await wrapper.setProps({ value: '23:00:00' })
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    await wrapper.get('button[aria-label="55分"]').trigger('click')
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['23:55:00'])
    await wrapper.setProps({ value: '23:55:00' })
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    await wrapper.get('input[aria-label="开始时间秒"]').trigger('focus')
    const dial = wrapper.get('.clock-dial')
    dial.element.getBoundingClientRect = () => ({ left: 0, top: 0, width: 240, height: 240 })
    await dial.trigger('pointerdown', { clientX: 240, clientY: 120, button: 0 })
    await dial.trigger('pointerup', { clientX: 240, clientY: 120 })
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['23:55:15'])
    const hour = wrapper.get('input[aria-label="开始时间时"]')
    await hour.setValue('9')
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['09:55:15'])
    const minute = wrapper.get('input[aria-label="开始时间分"]')
    await minute.setValue('05')
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['09:05:15'])
    const count = wrapper.emitted('update:value').length
    await hour.setValue('24')
    expect(wrapper.emitted('update:value')).toHaveLength(count)
    expect(hour.element.value).toBe('09')
    expect(wrapper.find('.clock-manual').exists()).toBe(false)
    expect(wrapper.find('.clock-panel small').exists()).toBe(false)
    wrapper.unmount()
  })

  it('禁用状态不允许表盘或手动输入产生变更', async () => {
    const wrapper = mount(ClockTimePicker, { props: { value: '12:00:00', disabled: true } })
    await wrapper.get('button[aria-label="55分"]').trigger('click')
    expect(wrapper.emitted('update:value')).toBeUndefined()
    wrapper.unmount()
  })

  it('从数字上起拖也捕获指针，末端圆点跟随移动，松开后的click不跳回原数字', async () => {
    const wrapper = mount(ClockTimePicker, { props: { value: '00:00:00', label: '结束时间' } })
    await wrapper.get('input[aria-label="结束时间时"]').trigger('focus')
    const dial = wrapper.get('.clock-dial')
    dial.element.getBoundingClientRect = () => ({ left: 0, top: 0, width: 240, height: 240 })
    dial.element.setPointerCapture = vi.fn()
    dial.element.hasPointerCapture = () => true
    dial.element.releasePointerCapture = vi.fn()
    await wrapper.get('button[aria-label="23时"]').trigger('pointerdown', { clientX: 72, clientY: 37, button: 0, pointerId: 1 })
    expect(dial.element.setPointerCapture).toHaveBeenCalledWith(1)
    await dial.trigger('pointermove', { clientX: 216, clientY: 120, pointerId: 1 })
    expect(wrapper.get('.clock-hand-knob').attributes('cx')).toBe('216')
    expect(wrapper.get('.clock-hand-knob').attributes('cy')).toBe('120')
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['15:00:00'])
    await dial.trigger('pointerup', { clientX: 120, clientY: 216, pointerId: 1 })
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['18:00:00'])
    wrapper.get('.clock-dial').element.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }))
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['18:00:00'])
    expect(dial.element.releasePointerCapture).toHaveBeenCalledWith(1)
    expect(wrapper.get('.clock-trigger').text()).toContain('18:00:00')
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    expect(wrapper.findAll('.clock-panel input')).toHaveLength(3)
    expect(wrapper.find('.clock-time-picker > input').exists()).toBe(false)
    wrapper.unmount()
  })

  it('拖动小时松手后才切分钟，选完分钟仍停留分钟且不改变秒', async () => {
    const wrapper = mount(ClockTimePicker, { props: { value: '03:20:45', label: '时间' } })
    await wrapper.get('input[aria-label="时间时"]').trigger('focus')
    const dial = wrapper.get('.clock-dial')
    dial.element.getBoundingClientRect = () => ({ left: 0, top: 0, width: 240, height: 240 })
    await dial.trigger('pointerdown', { clientX: 216, clientY: 120, button: 0 })
    await dial.trigger('pointermove', { clientX: 120, clientY: 216 })
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('时')
    await dial.trigger('pointerup', { clientX: 120, clientY: 216 })
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    await dial.trigger('pointerdown', { clientX: 216, clientY: 120, button: 0 })
    await dial.trigger('pointerup', { clientX: 216, clientY: 120 })
    expect(wrapper.emitted('update:value').at(-1)).toEqual(['18:15:45'])
    expect(wrapper.get('.clock-unit[data-active="true"]').text()).toBe('分')
    wrapper.unmount()
  })
})

describe('耗时时分秒滑条', () => {
  it('分钟仅在五分钟刻度附近轻微吸附，其他分钟和键盘逐分钟可用', async () => {
    const wrapper = mount(DurationPicker, { props: { value: 37, min: 1 } })
    const minute = wrapper.findAll('input[type="range"]')[1]
    await minute.setValue(13)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([817])
    await minute.setValue(14.5)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([937])
    expect(Number(minute.element.value)).toBe(14.75)
    await minute.setValue(16)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([997])
    await wrapper.setProps({ value: 997 })
    await minute.trigger('keydown', { key: 'ArrowRight' })
    expect(wrapper.emitted('update:value').at(-1)).toEqual([1057])
    expect(wrapper.text()).not.toContain('调整')
    expect(wrapper.find('.duration-sliders strong').exists()).toBe(false)
    wrapper.unmount()
  })
  it('滑条逐秒更新，保留人工输入并拒绝非法时长', async () => {
    const wrapper = mount(DurationPicker, { props: { value: 60, min: 1 } })
    const ranges = wrapper.findAll('input[type="range"]')
    expect(ranges).toHaveLength(3)
    await ranges[0].setValue(2)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([7260])
    await wrapper.setProps({ value: 7260 })
    await ranges[2].setValue(37)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([7297])
    const input = wrapper.get('input[aria-label="耗时"]')
    await input.setValue('00:03:20')
    expect(wrapper.emitted('update:value').at(-1)).toEqual([200])
    const count = wrapper.emitted('update:value').length
    await input.setValue('00:99:00')
    expect(wrapper.emitted('update:value')).toHaveLength(count)
    wrapper.unmount()
  })

  it('循环时长支持24小时，普通时长不溢出一天', async () => {
    const wrapper = mount(DurationPicker, { props: { value: 60, min: 1, max: 86400 } })
    await wrapper.findAll('input[type="range"]')[0].setValue(24)
    expect(wrapper.emitted('update:value').at(-1)).toEqual([86400])
    await wrapper.setProps({ max: 86399 })
    await wrapper.get('input[aria-label="耗时"]').setValue('24:00:00')
    expect(wrapper.emitted('update:value')).toHaveLength(1)
    wrapper.unmount()
  })
})
